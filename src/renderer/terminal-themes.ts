/** Resolves 'Auto' to a concrete theme name based on UI dark/light mode. */
export function resolveTerminalTheme(name: string, isDark: boolean): ITheme {
  if (name === 'Auto') {
    return isDark ? TERMINAL_THEMES.Dracula : TERMINAL_THEMES['GitHub Light'];
  }
  return TERMINAL_THEMES[name] ?? TERMINAL_THEMES.Dracula;
}

